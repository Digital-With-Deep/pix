#!/usr/bin/env node
// Generate the docs changelog page from the repo-root CHANGELOG.md.
// The page is a thin wrapper: frontmatter + a generated note + the changelog body
// (everything after the top-level "# Changelog" heading and its intro paragraph).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "..", "CHANGELOG.md");
const outDir = join(here, "..", "content", "docs");
const out = join(outDir, "changelog.mdx");

const raw = readFileSync(src, "utf8");

// Drop the leading "# Changelog" H1 and the intro lines up to the first "## " section,
// so the page keeps its own title/description and starts at the first release heading.
const firstSection = raw.indexOf("\n## ");
if (firstSection === -1) throw new Error("CHANGELOG.md has no '## ' sections");
const body = raw.slice(firstSection).trim();

const page = `---
title: Changelog
description: What changed in PIX, release by release.
---

{/* Generated by scripts/build-changelog.mjs from the repo-root CHANGELOG.md — edit that file instead. */}

Every notable change to PIX, newest first. The four \`@pix-ui/*\` packages are released together and follow [semantic versioning](https://semver.org).

${body}
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(out, page);
console.log(`@pix-ui/docs: changelog → content/docs/changelog.mdx (${body.split("\n## ").length - 1} prior sections)`);
