#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { createHighlighter } from "shiki";

const here = dirname(fileURLToPath(import.meta.url));
const examplesDir = join(here, "..", "registry", "examples");
const outDir = join(here, "..", "registry", "__generated__");

export function collectExamples() {
  const files = readdirSync(examplesDir);
  const entries = [];
  for (const f of files) {
    if (f.endsWith(".css.ts")) {
      const name = basename(f, ".css.ts");
      const mod = readFileSync(join(examplesDir, f), "utf8");
      // pull the exported `angular` template string for the code tab
      const m = /export const angular\s*=\s*`([\s\S]*?)`/.exec(mod);
      if (!m) throw new Error(`css example ${f} must export an \`angular\` template string`);
      entries.push({ name, lang: "html", importPath: `../examples/${f.replace(/\.ts$/, "")}`, source: m[1] });
    } else if (f.endsWith(".tsx")) {
      const name = basename(f, ".tsx");
      entries.push({
        name, lang: "tsx",
        importPath: `../examples/${basename(f, ".tsx")}`,
        source: readFileSync(join(examplesDir, f), "utf8"),
      });
    }
  }
  return entries.sort((a, b) => a.name.localeCompare(b.name));
}

export function buildRegistrySource(entries) {
  const seen = new Set();
  const imports = [];
  const records = [];
  entries.forEach((e, i) => {
    if (seen.has(e.name)) throw new Error(`duplicate registry name: ${e.name}`);
    seen.add(e.name);
    const id = `e${i}`;
    const hl = e.highlighted ? `, highlighted: ${JSON.stringify(e.highlighted)}` : "";
    if (e.lang === "tsx") {
      imports.push(`import ${id} from "${e.importPath}";`);
      records.push(`  ${JSON.stringify(e.name)}: { name: ${JSON.stringify(e.name)}, lang: "tsx", Component: ${id}, source: ${JSON.stringify(e.source)}${hl} },`);
    } else {
      imports.push(`import * as ${id} from "${e.importPath}";`);
      records.push(`  ${JSON.stringify(e.name)}: { name: ${JSON.stringify(e.name)}, lang: "html", html: ${id}.html, source: ${JSON.stringify(e.source)}${hl} },`);
    }
  });
  return `// Generated by build-registry.mjs — do not edit.\nimport * as React from "react";\n${imports.join("\n")}\n\nexport const registry = {\n${records.join("\n")}\n} as const;\n\nexport type RegistryName = keyof typeof registry;\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(outDir, { recursive: true });
  const entries = collectExamples();

  // Syntax-highlight every example once, dual light/dark themes (flipped via CSS).
  const highlighter = await createHighlighter({ themes: ["github-light", "github-dark"], langs: ["tsx", "html"] });
  for (const e of entries) {
    e.highlighted = highlighter.codeToHtml(e.source, {
      lang: e.lang === "tsx" ? "tsx" : "html",
      themes: { light: "github-light", dark: "github-dark" },
      defaultColor: false,
    });
  }
  highlighter.dispose();

  const src = buildRegistrySource(entries);
  writeFileSync(join(outDir, "index.ts"), src);
  writeFileSync(join(outDir, "names.json"), JSON.stringify(entries.map((e) => e.name)));
  console.log(`@pix-ui/docs: registry → ${entries.length} examples (highlighted)`);
}
